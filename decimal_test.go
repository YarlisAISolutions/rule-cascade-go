// The expected values in this file were computed with Python's decimal module, the arithmetic of
// the reference implementation: precision 34 for the operations, precision 15 for numbers leaving
// the engine, round half even. "error" marks an operation the reference refuses.

func mustDecimal(t *testing.T, s string) decimal {
	t.Helper()
	d, ok := parseDecimal(s)
	if !ok {
		t.Fatalf("parseDecimal(%q) failed", s)
	}
	return d
}

func outcome(d decimal, err error) string {
	if err != nil {
		return "error"
	}
	return d.String()
}

