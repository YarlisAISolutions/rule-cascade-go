func TestDecimalArithmetic(t *testing.T) {
	for _, c := range arithmeticCases {
		a, b := mustDecimal(t, c.a), mustDecimal(t, c.b)
		for _, op := range []struct {
			name string
			run  func(decimal) (decimal, error)
			want string
		}{{"add", a.add, c.add}, {"sub", a.sub, c.sub}, {"mul", a.mul, c.mul}, {"div", a.div, c.div}, {"rem", a.rem, c.rem}} {
			if got := outcome(op.run(b)); got != op.want {
				t.Errorf("%s %s %s = %s, want %s", c.a, op.name, c.b, got, op.want)
			}
		}
	}
}

